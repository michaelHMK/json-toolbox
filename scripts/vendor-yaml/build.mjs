import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const directory = fileURLToPath(new URL('.', import.meta.url));
const output = resolve(directory, '../../src/vendor');
const { metafile, outputFiles } = await build({
  absWorkingDir: directory,
  entryPoints: ['entry.js'],
  outfile: 'yaml.js',
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  banner: { js: '// Generated by scripts/vendor-yaml/build.mjs. Licenses: yaml.LICENSE.txt.' },
  metafile: true,
  write: false,
});

const packageDirs = new Set();
for (const [file, { bytesInOutput }] of Object.entries(metafile.outputs['yaml.js'].inputs)) {
  const match = file.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (bytesInOutput && match) packageDirs.add(match[1]);
}
const notices = [];
for (const packageDir of [...packageDirs].sort()) {
  const root = resolve(directory, packageDir);
  const { name, version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const license = await readFile(resolve(root, 'LICENSE'), 'utf8');
  notices.push(`${name} ${version}\n\n${license.trimEnd()}\n`);
}

await mkdir(output, { recursive: true });
await writeFile(resolve(output, 'yaml.js'), outputFiles[0].contents);
await writeFile(resolve(output, 'yaml.LICENSE.txt'), notices.join('\n'));
