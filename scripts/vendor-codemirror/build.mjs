import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const directory = fileURLToPath(new URL('.', import.meta.url));
const output = resolve(directory, '../../src/vendor');
const { metafile, outputFiles } = await build({
  absWorkingDir: directory,
  entryPoints: ['entry.js'],
  outfile: 'codemirror.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  banner: { js: '// Generated by scripts/vendor-codemirror/build.mjs. Licenses: codemirror.LICENSE.txt.' },
  metafile: true,
  write: false,
});

// esbuild reports inputs relative to absWorkingDir, with POSIX separators.
// Preserve the upstream notice of each package that contributed bundled code.
const packageDirs = new Set();
for (const [file, { bytesInOutput }] of Object.entries(metafile.outputs['codemirror.js'].inputs)) {
  const match = file.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (bytesInOutput && match) packageDirs.add(match[1]);
}
const notices = [];
for (const packageDir of [...packageDirs].sort()) {
  const root = resolve(directory, packageDir);
  const { name, version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const license = await readFile(resolve(root, 'LICENSE'), 'utf8');
  notices.push(`${name} ${version}\n\n${license.trimEnd()}\n`);
}
// The editor's grapheme and bidirectional bracket tables contain Unicode data.
const unicodeLicense = await readFile(resolve(directory, 'UNICODE-LICENSE.txt'), 'utf8');
notices.push(`Unicode Character Database (https://www.unicode.org/license.txt)\n\n${unicodeLicense.trimEnd()}\n`);

await mkdir(output, { recursive: true });
await writeFile(resolve(output, 'codemirror.js'), outputFiles[0].contents);
await writeFile(resolve(output, 'codemirror.LICENSE.txt'), notices.join('\n'));
